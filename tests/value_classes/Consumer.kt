package valueconsumer

import valuecases.*

fun main() {
    val id = Id(7)
    check(id.raw == 7)
    check(Secret(4).read() == 4)
    check(capture(id)() == id)
    check(id.toString() == "Id(raw=7)")
    check(id.add(2).raw == 9)
    check(id.format(listOf("yes")) == "yes")
    check(mixed(listOf("a","b"),null)[0].raw == 2)
    check(Mixed().keep(listOf("a"),null) == null)
    check(Mixed().keep(listOf("a"),id) == id)
    check(Id(7) == id)
    check(Id(8) != id)
    check(id.hashCode() == 7)
    check(createId(3).raw == 3)
    check(generic(id).value == id)
    check(list(id)[0] == id)
    check(fromAny(asAny(id)) == id)
    check(nullableId(null) == null)
    check(nullableId(id) == id)
    val text = Text("hello")
    check(text.toString() == "hello")
    check(nullableText(null) == null)
    check(nullableText(text) == text)
    val absent: MaybeText? = nullMaybe()
    val present: MaybeText? = boxedNullMaybe()
    check(absent == null)
    check(present != null)
    check(present!!.raw == null)
    check(nullableMaybeText(present) != null)
    val wide = Wide(Long.MIN_VALUE)
    check(wide.raw == Long.MIN_VALUE)
    check(asShow(wide).show() == "Wide-9223372036854775808")
    check(fromShow(asShow(wide)) == wide)
    val holder = Holder(id)
    check(holder.value == id)
    check(holder.capture()() == id)
    val pair = Pair(id, wide, text)
    check(pair.component1() == id)
    check(pair.component2() == wide)
    check(pair.copy(text = Text("new")).text.raw == "new")
    check(pair == Pair(id, wide, text))
    check(pair.toString() == "Pair(id=Id(raw=7), wide=Wide(raw=-9223372036854775808), text=hello)")
    Effects.count = 0
    val tracked = tracked(3)
    check(tracked.raw == 3)
    check(Effects.count == 1)
    val trackedAny: Any = tracked
    check((trackedAny as Tracked).raw == 3)
    check(Effects.count == 1)
    var caught = false
    try { tracked(-1) } catch (error: IllegalArgumentException) { caught = error.message == "negative" }
    check(caught)
    check(Effects.count == 2)
    println("OK")
}
