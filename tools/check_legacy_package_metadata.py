#!/usr/bin/env python3
import argparse
from collections import Counter
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import zipfile

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / 'tests/legacy_package_metadata'


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def relative(path):
    path = Path(path).absolute()
    return str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--candidate', type=Path, default=ROOT / 'target/release/korrust')
    parser.add_argument('--output', type=Path)
    parser.add_argument('--evidence-directory', type=Path)
    args = parser.parse_args()
    created = datetime.now(timezone.utc)
    stamp = created.strftime('%Y-%m-%dT%H%M%S%fZ') + '-legacy-package-metadata'
    directory = (args.output or ROOT / 'target/checks' / stamp).absolute()
    evidence = (args.evidence_directory or ROOT / 'reports/correctness' / stamp).absolute()
    directory.mkdir(parents=True, exist_ok=False)
    evidence.mkdir(parents=True, exist_ok=False)
    candidate = directory / 'korrust-frozen'
    shutil.copy2(args.candidate.resolve(), candidate)
    official = ROOT / 'references/kotlinc/bin/kotlinc'
    standard = ROOT / 'references/kotlinc/lib/kotlin-stdlib.jar'
    java = Path(os.environ['JAVA_HOME']) / 'bin'
    options = ['-language-version', '2.3', '-api-version', '2.3', '-jvm-target', '1.8']
    inputs = [*sorted((ROOT / 'src').rglob('*.rs')), *sorted(FIXTURES.iterdir()), ROOT / 'tests/legacy_package_metadata.rs', Path(__file__), ROOT / 'Cargo.toml', ROOT / 'Cargo.lock', ROOT / 'references/compiler.json', ROOT / 'references/sources.json']
    frozen = {relative(path): sha(path) for path in [*inputs, candidate, standard, ROOT / 'references/kotlinc/lib/kotlin-compiler.jar']}
    with zipfile.ZipFile(evidence / 'inputs.zip', 'w', zipfile.ZIP_DEFLATED) as archive:
        for path in inputs:
            archive.writestr(relative(path), path.read_bytes())
    report_path = evidence.with_suffix('.json')
    report = dict(schema_version=1, kind='correctness', created_at=created.isoformat(), status='running',
        compiler=dict(path=relative(candidate), sha256=sha(candidate), source_revision=subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()),
        reference_compiler=json.loads((ROOT / 'references/compiler.json').read_text()),
        frozen_input_hashes=frozen, input_bundle=dict(path=relative(evidence / 'inputs.zip'), sha256=sha(evidence / 'inputs.zip')),
        scope='Compiled Kotlin package imports for metadata versions 1.4 through 1.9 and 2.3: renamed facade and function, aliased imports, generic inference, named/default arguments, extension function, property, constant, type alias, annotation definition and multifile package parts',
        limitations=['Metadata generated by the pinned compiler using -Xmetadata-version; this is bounded schema compatibility evidence, not validation of every historical compiler', 'Existing member/JVM signature checks and unsupported-language boundaries still apply', 'No complete MockK execution, application compatibility or performance claim'],
        effective_options=dict(language_version='2.3', api_version='2.3', jvm_target='1.8'),
        cases=[], commands=[], reproduction_command=['python3', relative(__file__), '--candidate', relative(args.candidate), '--output', relative(directory), '--evidence-directory', relative(evidence)])

    def save():
        report['counts'] = dict(Counter(case['outcome'] for case in report['cases']))
        report_path.write_text(json.dumps(report, indent=2) + '\n')

    def run(label, command):
        command = [str(part) for part in command]
        result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, timeout=360)
        log = evidence / f'{len(report["commands"]):03d}.txt'
        log.write_text('$ ' + ' '.join(command) + '\n' + result.stdout + result.stderr)
        report['commands'].append(dict(label=label, argv=command, exit_code=result.returncode, log=relative(log)))
        save()
        assert result.returncode == 0, label + ': ' + result.stdout + result.stderr
        return result

    def case(name, operation):
        try:
            detail = operation()
            report['cases'].append(dict(id=name, outcome='pass', detail=detail))
        except Exception as error:
            report['cases'].append(dict(id=name, outcome='correctness_failure', detail=str(error)))
        save()

    save()
    for version in ['1.4.0', '1.5.0', '1.6.0', '1.7.0', '1.8.0', '1.9.0', '2.3.0']:
        def verify(version=version):
            workspace = directory / version
            workspace.mkdir()
            dependency = workspace / 'dependency'
            run(version + ' official dependency', [official, *[FIXTURES / name for name in ['Library.kt', 'First.kt', 'Second.kt']], '-d', dependency, '-Xmetadata-version=' + version, *options])
            cp = os.pathsep.join(map(str, [dependency, standard]))
            providers = [('official', workspace / 'official'), ('candidate', workspace / 'candidate')]
            run(version + ' official consumer', [official, FIXTURES / 'Consumer.kt', '-cp', cp, '-d', providers[0][1], *options])
            run(version + ' candidate consumer', [candidate, FIXTURES / 'Consumer.kt', '-cp', cp, '-d', providers[1][1]])
            if version == '1.7.0':
                jar = workspace / 'dependency.jar'
                with zipfile.ZipFile(jar, 'w', zipfile.ZIP_DEFLATED) as archive:
                    for path in sorted(dependency.rglob('*')):
                        if path.is_file():
                            archive.write(path, str(path.relative_to(dependency)))
                output = workspace / 'candidate-jar'
                run(version + ' candidate archive imports', [candidate, FIXTURES / 'Consumer.kt', '-cp', os.pathsep.join(map(str, [jar, standard])), '-d', output])
                providers.append(('candidate-jar', output))
            caller = workspace / 'caller'
            run(version + ' fixed Java caller against official', [java / 'javac', '-cp', os.pathsep.join(map(str, [providers[0][1], dependency, standard])), '-d', caller, FIXTURES / 'Calls.java'])
            signatures = []
            for name, output in providers:
                runtime = run(version + ' ' + name + ' independent runtime assertions', [java / 'java', '-Xverify:all', '-cp', os.pathsep.join(map(str, [caller, output, dependency, standard])), 'compatibility.consumer.Calls'])
                assert runtime.stdout == 'OK\n', runtime.stdout
                listing = run(version + ' ' + name + ' public JVM signatures', [java / 'javap', '-public', '-s', '-classpath', output, 'compatibility.consumer.ConsumerKt', 'compatibility.consumer.Tagged'])
                signatures.append(listing.stdout)
            assert all(listing == signatures[0] for listing in signatures), signatures
            return dict(dependency_hashes={str(path.relative_to(dependency)): sha(path) for path in sorted(dependency.rglob('*')) if path.is_file()}, caller_sha256={str(path.relative_to(caller)): sha(path) for path in caller.rglob('*.class')}, providers=[name for name, _ in providers], independent_assertions='value() == 103; label("meta") == "meta"; retained Marker.label == "older"; fixed Java caller and matching public JVM signatures')
        case('metadata_' + version, verify)
    changed = [name for name, digest in frozen.items() if sha(ROOT / name) != digest]
    report['cases'].append(dict(id='frozen_inputs', outcome='correctness_failure' if changed else 'pass', changed=changed))
    report['status'] = 'failed' if any(case['outcome'] == 'correctness_failure' for case in report['cases']) else 'complete'
    save()
    subprocess.run(['python3', ROOT / 'tools/reports.py'], cwd=ROOT, check=True)
    print(json.dumps(dict(report=relative(report_path), status=report['status'], counts=report['counts'])))
    return report['status'] != 'complete'


if __name__ == '__main__':
    raise SystemExit(main())
